export function findCaidpRI(entityName: string, customList?: CaidpEntity[]): CaidpEntity | undefined {
  if (!entityName) return undefined;
  const list = customList && customList.length > 0 ? customList : CAIDP_MASTER_DIRECTORY;
  const clean = entityName.toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, ' ')
    .trim();

  return list.find(ri => {
    const comp = ri.company_name.toLowerCase()
      .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]/g, ' ')
      .trim();
    return comp.includes(clean) || clean.includes(comp);
  });
}
